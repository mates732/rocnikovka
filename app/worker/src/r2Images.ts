/**
 * R2 image storage.
 *
 * Image bytes live in R2; metadata lives in D1. Object keys are always derived
 * from the server-generated image_id — never from user-supplied filenames — so
 * path traversal and bucket-wide enumeration are impossible.
 *
 * The bucket stays private. Reads go through the Worker route
 * GET /api/images/:imageId/file, which checks the D1 record first and only then
 * streams the object.
 */
import { ImageUploadError } from "./imageUploadErrors.js";

/** Minimal shape of the R2 bucket binding, so this layer is unit-testable. */
export interface R2BucketLike {
  put(
    key: string,
    value: ArrayBuffer | ArrayBufferView | string,
    options?: { httpMetadata?: { contentType?: string }; customMetadata?: Record<string, string> }
  ): Promise<unknown>;
  get(key: string): Promise<{ arrayBuffer(): Promise<ArrayBuffer>; httpMetadata?: { contentType?: string } } | null>;
  head(key: string): Promise<{ size: number } | null>;
  delete(key: string): Promise<void>;
}

export const MAX_IMAGE_UPLOAD_BYTES = 20 * 1024 * 1024; // 20 MiB

/** Content types accepted for RAW experimental photographs. */
export const ALLOWED_IMAGE_CONTENT_TYPES = [
  "image/jpeg",
  "image/png",
  "image/webp",
  "image/heic",
  "image/heif",
] as const;

export type AllowedImageContentType = (typeof ALLOWED_IMAGE_CONTENT_TYPES)[number];

/** Extension for each accepted content type, used for the object key suffix. */
const EXTENSION_BY_TYPE: Record<AllowedImageContentType, string> = {
  "image/jpeg": "jpg",
  "image/png": "png",
  "image/webp": "webp",
  "image/heic": "heic",
  "image/heif": "heif",
};

export function isAllowedImageContentType(value: string): value is AllowedImageContentType {
  return (ALLOWED_IMAGE_CONTENT_TYPES as readonly string[]).includes(value);
}

/**
 * Builds the R2 object key for an image.
 *
 * The key is `images/<image_id>.<ext>`. The image_id is generated by the server
 * from a timestamp + counter, so keys are unique and never attacker-controlled.
 */
export function buildImageObjectKey(imageId: string, contentType: string): string {
  if (!/^IMG-[0-9]{8}-[0-9]{6}-[A-Za-z0-9]+$/.test(imageId)) {
    throw new ImageUploadError("Invalid image id for object key", "id.invalid_format");
  }
  if (!isAllowedImageContentType(contentType)) {
    throw new ImageUploadError("Unsupported image content type", "image.invalid_content_type");
  }
  return `images/${imageId}.${EXTENSION_BY_TYPE[contentType]}`;
}

/** True when a stored key is well-formed (defensive check on read paths). */
export function isSafeImageObjectKey(key: string): boolean {
  return /^images\/IMG-[0-9]{8}-[0-9]{6}-[A-Za-z0-9]+\.(jpg|png|webp|heic|heif)$/.test(key);
}

export interface StoredImage {
  key: string;
  bytes: ArrayBuffer;
  contentType: string;
}

export class R2ImageStore {
  constructor(private readonly bucket: R2BucketLike) {}

  async put(key: string, bytes: ArrayBuffer, contentType: string): Promise<void> {
    if (!isSafeImageObjectKey(key)) {
      throw new ImageUploadError("Refusing unsafe image object key", "image.unsafe_key");
    }
    if (bytes.byteLength > MAX_IMAGE_UPLOAD_BYTES) {
      throw new ImageUploadError("Image exceeds maximum allowed size", "image.too_large");
    }
    await this.bucket.put(key, bytes, {
      httpMetadata: { contentType },
      customMetadata: { "stored-by": "phytometer-worker" },
    });
  }

  async get(key: string): Promise<StoredImage | null> {
    if (!isSafeImageObjectKey(key)) return null;
    const object = await this.bucket.get(key);
    if (!object) return null;
    return {
      key,
      bytes: await object.arrayBuffer(),
      contentType: object.httpMetadata?.contentType ?? "application/octet-stream",
    };
  }

  async exists(key: string): Promise<boolean> {
    if (!isSafeImageObjectKey(key)) return false;
    return (await this.bucket.head(key)) !== null;
  }
}
